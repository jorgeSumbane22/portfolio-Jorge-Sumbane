    const ATTRS = ['placeholder', 'aria-label', 'title', 'alt'];
    const PAGE = { title: '', desc: '' }; // título e descrição originais (PT) da página atual
    const norm = (s) => s.replace(/\s+/g, ' ').trim();
    // inglês -> português, para textos criados já em inglês (ex.: janela de detalhe)
    const PT_OF = {};
    Object.entries(EN).forEach(([pt, en]) => { if (en && !(en in PT_OF)) PT_OF[en] = pt; });
    const toOriginal = (value) => {
        const key = norm(value);
        if (key && !(key in EN) && key in PT_OF) {
            const lead = value.match(/^\s*/)[0];
            const trail = value.match(/\s*$/)[0];
            return lead + PT_OF[key] + trail;
        }
        return value;
    };
    const originalText = new WeakMap();   // nó de texto -> texto PT original
    const originalAttr = new WeakMap();   // elemento -> { atributo: valor PT }

    let lang = 'pt';

    function eachRoot(fn) {
        fn(document.head);
        fn(document.body);
        document.querySelectorAll('template').forEach((t) => fn(t.content));
    }

    function translateTextNodes(root) {
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
            acceptNode(node) {
                const p = node.parentElement;
                if (!p) return NodeFilter.FILTER_ACCEPT; // dentro de <template>
                if (p.closest('script, style, svg, .split, [data-no-i18n]')) return NodeFilter.FILTER_REJECT;
                return node.data.trim() ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
            }
        });
        const nodes = [];
        while (walker.nextNode()) nodes.push(walker.currentNode);
        nodes.forEach((node) => {
            if (!originalText.has(node)) originalText.set(node, toOriginal(node.data));
            const pt = originalText.get(node);
            if (lang === 'pt') { node.data = pt; return; }
            const key = norm(pt);
            if (Object.prototype.hasOwnProperty.call(EN, key)) {
                const lead = pt.match(/^\s*/)[0];
                const trail = pt.match(/\s*$/)[0];
                node.data = lead + EN[key] + trail;
            }
        });
    }

    function translateAttributes(root) {
        const sel = ATTRS.map((a) => `[${a}]`).join(',');
        root.querySelectorAll(sel).forEach((el) => {
            if (el.closest('[data-no-i18n]')) return;
            let saved = originalAttr.get(el);
            if (!saved) { saved = {}; originalAttr.set(el, saved); }
            ATTRS.forEach((a) => {
                if (!el.hasAttribute(a)) return;
                if (!(a in saved)) saved[a] = toOriginal(el.getAttribute(a));
                const pt = saved[a];
                const value = lang === 'pt' ? pt : (EN[norm(pt)] ?? pt);
                if (el.getAttribute(a) !== value) el.setAttribute(a, value);
            });
        });
    }

    function apply(next, save) {
        lang = next === 'en' ? 'en' : 'pt';
        const s = STRINGS[lang];
        document.documentElement.lang = lang === 'en' ? 'en' : 'pt';
        // cada página guarda o seu título PT; o inglês vem de data-title-en (ou do título geral)
        const metaDesc = document.querySelector('meta[name="description"]');
        if (!PAGE.title) { PAGE.title = document.title; PAGE.desc = metaDesc ? metaDesc.content : ''; }
        const titleEn = document.documentElement.getAttribute('data-title-en');
        if (lang === 'pt') {
            document.title = PAGE.title;
            if (metaDesc) metaDesc.content = PAGE.desc;
        } else {
            document.title = titleEn || s.title;
            if (metaDesc && !titleEn) metaDesc.content = s.description;
        }

        eachRoot((root) => { translateTextNodes(root); translateAttributes(root); });

        const btn = document.getElementById('langToggle');
        const label = document.getElementById('langLabel');
        if (label) label.textContent = s.langLabel;
        if (btn) btn.setAttribute('aria-label', s.langAria);

        if (save) {
            try { localStorage.setItem('lang', lang); } catch (e) { /* ignore */ }
            // atualiza o endereço (?lang=en) para se poder partilhar a versão inglesa
            try {
                const url = new URL(window.location.href);
                if (lang === 'en') url.searchParams.set('lang', 'en'); else url.searchParams.delete('lang');
                history.replaceState(null, '', url);
            } catch (e) { /* ignore */ }
        }
        document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
    }

    function initialLang() {
        try {
            const q = new URLSearchParams(window.location.search).get('lang');
            if (q === 'en' || q === 'pt') return q;
            const saved = localStorage.getItem('lang');
            if (saved === 'en' || saved === 'pt') return saved;
        } catch (e) { /* ignore */ }
        // visitantes com o navegador noutra língua veem a versão inglesa
        return (navigator.language || 'pt').toLowerCase().startsWith('pt') ? 'pt' : 'en';
    }

    window.I18N = {
        get lang() { return lang; },
        t(key) { return STRINGS[lang][key] ?? STRINGS.pt[key] ?? key; },
        set(next) { apply(next, true); },
        refresh(root) { translateTextNodes(root); translateAttributes(root); }
    };

